"""Generate docs/coverage.md: what the classifier does for each Annex III point.

Every row is computed from the code, not written by hand:
- citation and label come from ``catalog.ANNEX_III``;
- the outcome is ``classify()`` on a minimal profile naming only that area;
- examples are the ``examples/`` and ``examples/guidance/`` files that use it;
- tests are the ``tests/`` files that reference the area by enum name or value.

Run ``python scripts/build_coverage.py`` after changing the catalog, rules,
examples or tests; ``tests/test_coverage.py`` fails when the file is stale.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from eu_ai_act_classifier import AnnexIII, SystemProfile, classify  # noqa: E402
from eu_ai_act_classifier.catalog import ANNEX_III  # noqa: E402

OUTPUT = ROOT / "docs" / "coverage.md"

HEADER = """# Annex III coverage

Generated by `scripts/build_coverage.py` from the code; do not edit by hand.
`tests/test_coverage.py` fails when this file is out of date.

For each Annex III point (Art. 6(2) AIA) the table shows the citation the
classifier emits, what `classify()` returns for a minimal profile that names
only that point (no roles, no Art. 6(3) derogation facts), and which bundled
examples and tests exercise it. A minimal profile is a screening input, not a
legal conclusion; a lawyer reviews every result.

| Point | Citation | Area | Minimal-profile outcome | Examples | Tests |
|---|---|---|---|---|---|
"""


def _files_mentioning(paths: list[Path], needles: list[str]) -> list[str]:
    hits = []
    for path in paths:
        text = path.read_text(encoding="utf-8")
        if any(needle in text for needle in needles):
            hits.append(path.relative_to(ROOT).as_posix())
    return sorted(hits)


def build() -> str:
    examples = sorted((ROOT / "examples").rglob("*.json"))
    tests = sorted((ROOT / "tests").glob("test_*.py"))
    rows = []
    for area in AnnexIII:
        cited, label = ANNEX_III[area]
        citation = cited.render()
        report = classify(SystemProfile(name="coverage", annex_iii_area=area))
        outcome = f"{report.risk_tier.value}, {report.disposition.value}"
        ex = _files_mentioning(examples, [f'"{area.value}"'])
        ts = _files_mentioning(tests, [f"AnnexIII.{area.name}", f'"{area.value}"'])
        rows.append(
            f"| `{area.value}` | {citation} | {label} | {outcome} | "
            f"{'<br>'.join(f'`{e}`' for e in ex) or 'none'} | "
            f"{'<br>'.join(f'`{t}`' for t in ts) or 'none'} |"
        )
    covered_ex = sum(1 for row in rows if row.split("|")[5].strip() != "none")
    covered_ts = sum(1 for row in rows if row.split("|")[6].strip() != "none")
    footer = (
        f"\n{len(rows)} points listed; {covered_ex} have a bundled example and "
        f"{covered_ts} are referenced by a test. Points without an example or "
        "test are classified by the same generic Annex III rule as the others; "
        "`tests/test_coverage.py` checks the minimal-profile outcome of every "
        "point.\n"
    )
    return HEADER + "\n".join(rows) + "\n" + footer


if __name__ == "__main__":
    OUTPUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
